// F16 클립보드 기록. 근거: intent/F16-클립보드/

struct ClipItem: Codable, Equatable {
    enum Kind: String, Codable { case text, image, files }
    var id = UUID()
    var kind: Kind
    var text: String?
    var files: [String]?
    /// 이미지: 저장 폴더 안 파일 이름, `hash`로 같은 그림을 알아본다
    var image: String?
    var hash: String?
    var date = Date()
    var pinned = false

    /// 같은 내용인지(시각·고정과 상관없이)
    func sameContent(_ o: ClipItem) -> Bool {
        kind == o.kind && text == o.text && files == o.files && hash == o.hash
    }

    var preview: String {
        switch kind {
        case .text: (text ?? "").replacingOccurrences(of: "\n", with: " ").trimmingCharacters(in: .whitespaces)
        case .files: (files ?? []).map { URL(fileURLWithPath: $0).lastPathComponent }.joined(separator: ", ")
        case .image: "이미지"
        }
    }
}

/// 기록 목록 규칙(순수, 자체 검사 대상)
struct ClipHistory {
    var items: [ClipItem] = []
    var limit = 50

    /// 맨 위에 넣는다. 같은 내용이 있으면 그것을 맨 위로. 넘치면 고정 아닌 오래된 것부터 지우고, 지운 이미지 파일 이름을 돌려준다.
    @discardableResult
    mutating func insert(_ item: ClipItem) -> [String] {
        var item = item
        if let i = items.firstIndex(where: { $0.sameContent(item) }) {
            let old = items.remove(at: i)
            item.id = old.id
            item.pinned = old.pinned
            if item.image != old.image, let img = item.image { // 같은 그림을 새 파일로 받았으면 새 파일은 버린다
                item.image = old.image
                items.insert(item, at: 0)
                return [img]
            }
        }
        items.insert(item, at: 0)
        var dropped: [String] = []
        while items.filter({ !$0.pinned }).count > limit, let i = items.lastIndex(where: { !$0.pinned }) {
            if let img = items[i].image { dropped.append(img) }
            items.remove(at: i)
        }
        return dropped
    }

    /// 검색: 대소문자 무시, 고정 먼저
    func search(_ q: String) -> [ClipItem] {
        let q = q.trimmingCharacters(in: .whitespaces)
        let hit = q.isEmpty ? items : items.filter { $0.preview.range(of: q, options: [.caseInsensitive, .widthInsensitive, .diacriticInsensitive]) != nil }
        return hit.filter(\.pinned) + hit.filter { !$0.pinned }
    }

    /// 비밀번호 관리자 등이 기록하지 말라고 표시한 복사
    static func isConcealed(types: [String]) -> Bool {
        let skip: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                                 "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"]
        return types.contains { skip.contains($0) }
    }
}

/// 기록 저장(내 Mac에만): history.json + 이미지 PNG
final class ClipStore {
    static let shared = ClipStore()
    let folder: URL
    private(set) var history = ClipHistory()
    var onChange: () -> Void = {}
    private var saveWork: DispatchWorkItem?

    static var limit: Int {
        get { UserDefaults.standard.object(forKey: "clipLimit") as? Int ?? 50 }
        set { UserDefaults.standard.set(newValue, forKey: "clipLimit"); shared.update { $0.limit = newValue; $0.insertNothing() } }
    }

    init(folder: URL = Paths.support.appendingPathComponent("Clipboard")) {
        self.folder = folder
        // 복사한 내용이 들어 있으므로 나만 읽게
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try? FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: folder.path)
        if let data = try? Data(contentsOf: folder.appendingPathComponent("history.json")),
           let items = try? JSONDecoder().decode([ClipItem].self, from: data) {
            history.items = items
        }
        history.limit = UserDefaults.standard.object(forKey: "clipLimit") as? Int ?? 50
    }

    func add(_ item: ClipItem) {
        removeFiles(history.insert(item))
        changed()
    }

    func update(_ f: (inout ClipHistory) -> Void) {
        let before = Set(history.items.compactMap(\.image))
        f(&history)
        removeFiles(Array(before.subtracting(history.items.compactMap(\.image))))
        changed()
    }

    func imageURL(_ name: String) -> URL { folder.appendingPathComponent(name) }

    private func removeFiles(_ names: [String]) {
        for n in names { try? FileManager.default.removeItem(at: imageURL(n)) }
    }

    private func changed() {
        onChange()
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.save() }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5, execute: work)
    }

    func save() {
        guard let data = try? JSONEncoder().encode(history.items) else { return }
        let url = folder.appendingPathComponent("history.json")
        try? data.write(to: url, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
}

private extension ClipHistory {
    /// 개수를 줄였을 때 바로 자르기
    mutating func insertNothing() {
        while items.filter({ !$0.pinned }).count > limit, let i = items.lastIndex(where: { !$0.pinned }) { items.remove(at: i) }
    }
}

/// 클립보드 바뀜을 0.5초마다 확인해 기록에 넣는다
final class ClipWatcher {
    static let shared = ClipWatcher()
    private var lastCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    /// 우리가 기록에서 다시 올린 changeCount(다시 기록하지 않음)
    private var ours: Int?
    var onCopy: (ClipItem) -> Void = { _ in }

    static var enabled: Bool {
        get { UserDefaults.standard.object(forKey: "clipOn") as? Bool ?? true }
        set { UserDefaults.standard.set(newValue, forKey: "clipOn"); shared.apply() }
    }

    func apply() {
        if Self.enabled, timer == nil {
            lastCount = NSPasteboard.general.changeCount
            timer = Ticker.every("복사한 것 확인하기", 0.5) { [weak self] _ in self?.check() }
        } else if !Self.enabled {
            timer?.invalidate()
            timer = nil
        }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        if ours == lastCount { return }
        let types = (pb.types ?? []).map(\.rawValue)
        guard !ClipHistory.isConcealed(types: types), let item = read(pb) else { return }
        ClipStore.shared.add(item)
        onCopy(item)
    }

    private func read(_ pb: NSPasteboard) -> ClipItem? {
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return ClipItem(kind: .files, files: urls.map(\.path))
        }
        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), data.count <= 10_000_000,
           pb.string(forType: .string) == nil,
           let png = data.starts(with: [0x89, 0x50, 0x4E, 0x47]) ? data : NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) {
            let name = UUID().uuidString + ".png"
            guard (try? png.write(to: ClipStore.shared.imageURL(name))) != nil else { return nil }
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: ClipStore.shared.imageURL(name).path)
            let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
            return ClipItem(kind: .image, image: name, hash: hash)
        }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, s.utf8.count <= 1_000_000 {
            return ClipItem(kind: .text, text: s)
        }
        return nil
    }

    /// 기록의 항목을 클립보드 맨 위로(다시 기록되지 않게 표시)
    func put(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text: pb.setString(item.text ?? "", forType: .string)
        case .files: pb.writeObjects((item.files ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let name = item.image, let data = try? Data(contentsOf: ClipStore.shared.imageURL(name)) { pb.setData(data, forType: .png) }
        }
        ours = pb.changeCount
        lastCount = pb.changeCount
        var top = item
        top.date = Date()
        ClipStore.shared.add(top)
    }
}

/// 전역 단축키(Carbon, 권한 필요 없음)
final class HotKey {
    static let shared = HotKey()
    private var handler: EventHandlerRef?
    var onPress: () -> Void = {}
    private(set) var registered = false

    /// 저장된 단축키: 기본 ⌘⇧C(keyCode 8)
    static var keyCode: UInt32 {
        get { UInt32(UserDefaults.standard.object(forKey: "clipKeyCode") as? Int ?? kVK_ANSI_C) }
        set { UserDefaults.standard.set(Int(newValue), forKey: "clipKeyCode") }
    }
    static var modifiers: UInt32 {
        get { UInt32(UserDefaults.standard.object(forKey: "clipKeyMods") as? Int ?? (cmdKey | shiftKey)) }
        set { UserDefaults.standard.set(Int(newValue), forKey: "clipKeyMods") }
    }

    /// 다시 등록. 다른 앱이 쓰고 있으면 false.
    @discardableResult
    func register() -> Bool {
        unregister()
        guard ClipWatcher.enabled else { return false }
        registered = add(id: 1, keyCode: Self.keyCode, modifiers: Self.modifiers) { HotKey.shared.onPress() }
        return registered
    }

    func unregister() {
        remove(id: 1)
        registered = false
    }

    // 여러 단축키(F15 창 정리도 씀): id → 등록·동작
    private var refs: [UInt32: EventHotKeyRef] = [:]
    private var actions: [UInt32: () -> Void] = [:]

    /// 등록. 다른 앱이 같은 키를 쓰고 있으면 false.
    func add(id: UInt32, keyCode: UInt32, modifiers: UInt32, action: @escaping () -> Void) -> Bool {
        remove(id: id)
        if handler == nil {
            var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
            InstallEventHandler(GetApplicationEventTarget(), { _, event, _ in
                var hk = EventHotKeyID()
                GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID), nil, MemoryLayout<EventHotKeyID>.size, nil, &hk)
                let id = hk.id
                DispatchQueue.main.async { HotKey.shared.actions[id]?() }
                return noErr
            }, 1, &spec, nil, &handler)
        }
        var ref: EventHotKeyRef?
        guard RegisterEventHotKey(keyCode, modifiers, EventHotKeyID(signature: OSType(0x5441534B), id: id), GetApplicationEventTarget(), 0, &ref) == noErr, let ref else { return false }   // 'TASK'
        refs[id] = ref
        actions[id] = action
        return true
    }

    func remove(id: UInt32) {
        if let r = refs.removeValue(forKey: id) { UnregisterEventHotKey(r) }
        actions[id] = nil
    }

    /// "⌘⇧C" 같은 표시
    static func title(keyCode: UInt32 = keyCode, modifiers m: UInt32 = modifiers) -> String {
        var s = ""
        if m & UInt32(controlKey) != 0 { s += "⌃" }
        if m & UInt32(optionKey) != 0 { s += "⌥" }
        if m & UInt32(shiftKey) != 0 { s += "⇧" }
        if m & UInt32(cmdKey) != 0 { s += "⌘" }
        let special: [Int: String] = [kVK_LeftArrow: "←", kVK_RightArrow: "→", kVK_UpArrow: "↑", kVK_DownArrow: "↓", kVK_Return: "↩", kVK_Delete: "⌫", kVK_ForwardDelete: "⌦", kVK_Space: "Space", kVK_Escape: "⎋", kVK_Tab: "⇥", kVK_Home: "↖", kVK_End: "↘"]
        if let k = special[Int(keyCode)] { return s + k }
        let src = TISCopyCurrentASCIICapableKeyboardLayoutInputSource().takeRetainedValue()
        if let ptr = TISGetInputSourceProperty(src, kTISPropertyUnicodeKeyLayoutData) {
            let layout = unsafeBitCast(ptr, to: CFData.self)
            var dead: UInt32 = 0
            var chars = [UniChar](repeating: 0, count: 4)
            var len = 0
            let ok = CFDataGetBytePtr(layout).withMemoryRebound(to: UCKeyboardLayout.self, capacity: 1) {
                UCKeyTranslate($0, UInt16(keyCode), UInt16(kUCKeyActionDisplay), 0, UInt32(LMGetKbdType()), OptionBits(kUCKeyTranslateNoDeadKeysBit), &dead, 4, &len, &chars)
            }
            if ok == noErr, len > 0 { return s + String(utf16CodeUnits: chars, count: len).uppercased() }
        }
        return s + "#\(keyCode)"
    }

    static func cocoaModifiers(_ m: UInt32) -> NSEvent.ModifierFlags {
        var f: NSEvent.ModifierFlags = []
        if m & UInt32(cmdKey) != 0 { f.insert(.command) }
        if m & UInt32(shiftKey) != 0 { f.insert(.shift) }
        if m & UInt32(optionKey) != 0 { f.insert(.option) }
        if m & UInt32(controlKey) != 0 { f.insert(.control) }
        return f
    }

    static func carbonModifiers(_ f: NSEvent.ModifierFlags) -> UInt32 {
        var m: UInt32 = 0
        if f.contains(.command) { m |= UInt32(cmdKey) }
        if f.contains(.shift) { m |= UInt32(shiftKey) }
        if f.contains(.option) { m |= UInt32(optionKey) }
        if f.contains(.control) { m |= UInt32(controlKey) }
        return m
    }
}

/// 기록 창: 검색 + 목록. 고르면 클립보드 맨 위로 올리고 닫는다(붙여넣기는 사용자가 ⌘V).
final class ClipWindow: NSObject, NSSearchFieldDelegate, NSTableViewDataSource, NSTableViewDelegate {
    static let shared = ClipWindow()
    private var panel: FloatingPanel?
    private let search = NSSearchField()
    private let table = NSTableView()
    private var shown: [ClipItem] = []
    private var previousApp: NSRunningApplication?
    private var monitors: [Any] = []
    private static let width: CGFloat = 440, rowHeight: CGFloat = 40, maxRows = 9

    var isOpen: Bool { panel != nil }

    func toggle() { isOpen ? close(restore: true) : open() }

    func open() {
        guard panel == nil else { return }
        previousApp = NSWorkspace.shared.frontmostApplication
        let height = 52 + Self.rowHeight * CGFloat(Self.maxRows) + 8
        let p = FloatingPanel(size: CGSize(width: Self.width, height: height))
        p.keyable = true
        p.level = .popUpMenu
        let screen = NSScreen.screens.first { $0.frame.contains(NSEvent.mouseLocation) } ?? NSScreen.main ?? NSScreen.screens[0]
        let v = screen.visibleFrame
        p.setFrameOrigin(CGPoint(x: v.midX - Self.width / 2, y: v.maxY - v.height / 3 - height / 2))

        let effect = NSVisualEffectView(frame: CGRect(x: 0, y: 0, width: Self.width, height: height))
        effect.material = .hudWindow
        effect.state = .active
        effect.wantsLayer = true
        effect.layer?.cornerRadius = 14
        effect.layer?.masksToBounds = true

        search.frame = CGRect(x: 12, y: height - 44, width: Self.width - 24, height: 32)
        search.placeholderString = "복사한 것 검색 · ↩ 고르기 · ⌘P 고정 · ⌫ 지우기"
        search.font = .systemFont(ofSize: 15)
        search.delegate = self
        search.stringValue = ""
        effect.addSubview(search)

        let scroll = NSScrollView(frame: CGRect(x: 6, y: 6, width: Self.width - 12, height: height - 58))
        scroll.drawsBackground = false
        scroll.hasVerticalScroller = true
        table.headerView = nil
        table.backgroundColor = .clear
        table.rowHeight = Self.rowHeight
        table.intercellSpacing = .zero
        table.style = .plain
        if table.tableColumns.isEmpty {
            let col = NSTableColumn(identifier: .init("c"))
            col.width = Self.width - 30
            table.addTableColumn(col)
        }
        table.dataSource = self
        table.delegate = self
        table.target = self
        table.action = #selector(clicked)
        scroll.documentView = table
        effect.addSubview(scroll)
        p.contentView = effect
        panel = p
        reload()

        NSApp.activate(ignoringOtherApps: true)   // 바로 검색어를 칠 수 있게
        p.makeKeyAndOrderFront(nil)
        p.makeFirstResponder(search)
        monitors = [
            NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] e in self?.key(e) == true ? nil : e },
            NSEvent.addGlobalMonitorForEvents(matching: [.leftMouseDown, .rightMouseDown]) { [weak self] _ in self?.close(restore: false) },
        ].compactMap { $0 }
        ClipStore.shared.onChange = { [weak self] in self?.reload() }
    }

    func close(restore: Bool) {
        monitors.forEach(NSEvent.removeMonitor)
        monitors = []
        panel?.orderOut(nil)
        panel = nil
        ClipStore.shared.onChange = {}
        if restore { previousApp?.activate() }
        previousApp = nil
    }

    private func reload() {
        let selected = table.selectedRow
        shown = ClipStore.shared.history.search(search.stringValue)
        table.reloadData()
        if !shown.isEmpty { table.selectRowIndexes([min(max(selected, 0), shown.count - 1)], byExtendingSelection: false) }
    }

    func controlTextDidChange(_ obj: Notification) {
        shown = ClipStore.shared.history.search(search.stringValue)
        table.reloadData()
        if !shown.isEmpty { table.selectRowIndexes([0], byExtendingSelection: false) }
    }

    /// 창의 키: ↑↓ ↩ Esc ⌘P ⌫(검색 칸이 비었을 때) 1~9(⌘와 함께)
    private func key(_ e: NSEvent) -> Bool {
        guard panel?.isKeyWindow == true else { return false }
        // 한글을 조합하는 중이면 입력기에 맡긴다(⌫가 기록을 지우거나 ↩가 엉뚱한 줄을 고르지 않게)
        if (search.currentEditor() as? NSTextView)?.hasMarkedText() == true { return false }
        let row = table.selectedRow
        switch Int(e.keyCode) {
        case kVK_Escape: close(restore: true); return true
        case kVK_DownArrow: select(row + 1); return true
        case kVK_UpArrow: select(row - 1); return true
        case kVK_Return, kVK_ANSI_KeypadEnter: pick(row); return true
        case kVK_Delete where search.stringValue.isEmpty || e.modifierFlags.contains(.command):
            guard shown.indices.contains(row) else { return false }
            let id = shown[row].id
            ClipStore.shared.update { $0.items.removeAll { $0.id == id } }
            return true
        default: break
        }
        if e.modifierFlags.contains(.command) {
            // 키 코드로 본다(한글 자판에서도 ⌘P·⌘1~9가 되게)
            if Int(e.keyCode) == kVK_ANSI_P, shown.indices.contains(row) {
                let id = shown[row].id
                ClipStore.shared.update { h in if let i = h.items.firstIndex(where: { $0.id == id }) { h.items[i].pinned.toggle() } }
                return true
            }
            let digits = [kVK_ANSI_1, kVK_ANSI_2, kVK_ANSI_3, kVK_ANSI_4, kVK_ANSI_5, kVK_ANSI_6, kVK_ANSI_7, kVK_ANSI_8, kVK_ANSI_9]
            if let n = digits.firstIndex(of: Int(e.keyCode)) { pick(n); return true }
        }
        return false
    }

    private func select(_ i: Int) {
        guard !shown.isEmpty else { return }
        let i = min(max(i, 0), shown.count - 1)
        table.selectRowIndexes([i], byExtendingSelection: false)
        table.scrollRowToVisible(i)
    }

    @objc private func clicked() { pick(table.clickedRow) }

    private func pick(_ i: Int) {
        guard shown.indices.contains(i) else { return }
        ClipWatcher.shared.put(shown[i])
        close(restore: true)
    }

    func numberOfRows(in tableView: NSTableView) -> Int { shown.count }

    private static let relative: RelativeDateTimeFormatter = { let f = RelativeDateTimeFormatter(); f.unitsStyle = .short; return f }()
    /// 이미지 줄의 작은 미리보기(한 번 줄여 두고 다시 쓴다)
    private static var thumbs: [String: NSImage] = [:]
    private static func thumb(_ name: String) -> NSImage? {
        if let t = thumbs[name] { return t }
        guard let src = CGImageSourceCreateWithURL(ClipStore.shared.imageURL(name) as CFURL, nil),
              let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, [kCGImageSourceCreateThumbnailFromImageAlways: true,
                                                                    kCGImageSourceThumbnailMaxPixelSize: 64] as CFDictionary) else { return nil }
        let img = NSImage(cgImage: cg, size: NSSize(width: 24, height: 24))
        thumbs[name] = img
        return img
    }

    func tableView(_ tableView: NSTableView, viewFor tableColumn: NSTableColumn?, row: Int) -> NSView? {
        let item = shown[row]
        let cell = NSView(frame: CGRect(x: 0, y: 0, width: Self.width - 30, height: Self.rowHeight))
        let icon = NSImageView(frame: CGRect(x: 8, y: 8, width: 24, height: 24))
        icon.imageScaling = .scaleProportionallyUpOrDown
        switch item.kind {
        case .text: icon.image = NSImage(systemSymbolName: "text.alignleft", accessibilityDescription: "글자")
        case .files: icon.image = NSImage(systemSymbolName: "doc", accessibilityDescription: "파일")
        case .image: icon.image = item.image.flatMap(Self.thumb) ?? NSImage(systemSymbolName: "photo", accessibilityDescription: "이미지")
        }
        icon.contentTintColor = .secondaryLabelColor
        cell.addSubview(icon)
        let text = NSTextField(labelWithString: (row < 9 ? "\(row + 1)  " : "   ") + String(item.preview.prefix(200)))
        text.lineBreakMode = .byTruncatingTail
        text.font = .systemFont(ofSize: 13)
        text.frame = CGRect(x: 40, y: 11, width: Self.width - 30 - 40 - 70, height: 18)
        cell.addSubview(text)
        let when = NSTextField(labelWithString: (item.pinned ? "📌 " : "") + Self.relative.localizedString(for: item.date, relativeTo: Date()))
        when.font = .systemFont(ofSize: 11)
        when.textColor = .secondaryLabelColor
        when.alignment = .right
        when.frame = CGRect(x: Self.width - 30 - 72, y: 12, width: 66, height: 16)
        cell.addSubview(when)
        return cell
    }
}
